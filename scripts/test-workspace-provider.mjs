import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import vm from 'node:vm';
import ts from 'typescript';
const require = createRequire(import.meta.url);
const code = ts.transpileModule(await readFile(new URL('../src/components/workspace-provider.tsx',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,jsx:ts.JsxEmit.ReactJSX}}).outputText;
let now=0, refreshes=0, effect, interval, snapshot;
const events = new Map();
const document = {visibilityState:'visible',addEventListener:(name,fn)=>events.set(name,fn),removeEventListener:name=>events.delete(name)};
const window = {setInterval:fn=>{interval=fn;return 1;},clearInterval:()=>{interval=null;},addEventListener:document.addEventListener,removeEventListener:document.removeEventListener};
const exports = {};
vm.runInNewContext(code,{exports,document,window,Date:{now:()=>now},require:name=>{
 if(name==='react') return {...require('react'),useEffect:fn=>{effect=fn;},useContext:()=>snapshot};
 if(name==='next/navigation') return {useRouter:()=>({refresh:()=>refreshes++})};
 if(name==='@/components/layout/app-shell') return {AppShell:()=>null};
 if(name==='@/components/workbench') return {Workbench:()=>null};
 return require(name);
}});
snapshot={workspace:{id:'a',name:'A',homeView:'management'},userId:'user-a',email:'a@example.test',data:{books:[{id:'book-a'}]},error:null,loadedAt:0};
exports.WorkspaceProvider({value:snapshot,loadedAt:0,children:null});
const cleanup=effect();
now=30000;interval();assert.equal(refreshes,0);
now=60000;interval();assert.equal(refreshes,1);
now=90000;events.get('focus')();assert.equal(refreshes,1);
document.visibilityState='hidden';now=700000;interval();assert.equal(refreshes,1);
document.visibilityState='visible';events.get('visibilitychange')();assert.equal(refreshes,2);
const first=exports.WorkspacePage({route:'livros',id:'book-a'});
assert.equal(first.props.data,snapshot.data);
snapshot={...snapshot,workspace:{id:'b'},data:{books:[{id:'book-b'}]}};
const second=exports.WorkspacePage({route:'livros'});
assert.equal(second.props.data.books[0].id,'book-b');
cleanup();assert.equal(interval,null);assert.equal(events.size,0);
console.log('PASS refresh interval, hidden tabs, focus renewal, cleanup and latest workspace snapshot');
